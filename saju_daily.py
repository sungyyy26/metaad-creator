def _digest(*parts):
    return hashlib.sha256("|".join(str(p) for p in parts).encode()).digest()


def score100(fortune, seed):
    """1~5점 네 영역 합(4~20)을 40~97로 펴고, 사람·날짜별 흔들림을 더한다. 아주 드물게 100점."""
    d = _digest(seed, fortune["date"], "score")
    base = 43 + (sum(fortune["scores"].values()) - 4) * 55 / 16
    score = int(round(base + (d[0] % 13) - 6))
    if score >= 88 and d[1] % 9 == 0:   # 좋은 날 중에서도 1/9 확률 — 운세왕 잭팟
        return 100
    return max(32, min(99, score))


def grade(score):
    for low, name, stamp in GRADES:
        if score >= low:
            return name, stamp
    return GRADES[-1][1], GRADES[-1][2]


def today_card(chart, fortune, seed):
    d = _digest(seed, fortune["date"], "card")
    score = score100(fortune, seed)
    g, stamp = grade(score)
    god = fortune["ten_god"]
    group = GROUP_OF[god]
    lucky = chart["lucky_element"]
    today_els = {fortune["pillar"]["stem"] // 2}
    office = []
    for i, (label, emoji, boost, low, high) in enumerate(OFFICE):
        v = 30 + (d[i] % 41) + (22 if group in boost or god in boost else 0) + (score - 65) // 4
        if label == "상사 레이더":   # 높을수록 '주의' — 점수가 좋으면 레이더는 조용
            v = 25 + (d[i] % 45) + (25 if group == "관성" else 0) - (score - 65) // 4
        v = max(3, min(99, v))
        office.append({"label": label, "emoji": emoji, "value": v,
                       "comment": high if v >= 60 else low, "warn": label == "상사 레이더"})
    tags = HASHTAGS[group]
    picks = [tags[d[10] % 6], tags[(d[10] + 1 + d[11] % 4) % 6]]
    do, dont = DO_DONT[god]
    return {
        "score": score, "grade": g, "stamp": stamp,
        "line": ONE_LINERS[g][d[6] % len(ONE_LINERS[g])],
        "drink": DRINKS[lucky][d[7] % 4],
        "lunch": LUNCH[(lucky + (1 if lucky in today_els else 0)) % 5][d[8] % 5],
        "item": ITEMS[lucky][d[9] % 4],
        "time": LUCKY_TIMES[d[12] % len(LUCKY_TIMES)],
        "number": 1 + d[13] % 45,
        "hashtags": picks + ["#" + chart["day_animal"].replace(" ", "")],
        "do": do, "dont": dont,
        "office": office,
        "jackpot": score == 100,
    }


def guardian(me_chart, today, others):
    """오늘의 귀인 팀원 — 궁합 점수 + 내게 필요한 오행을 가진 사람 + 날짜별 흔들림.
    others: [(profile_id, name, chart, compat_score)]"""
    best = None
    for pid, name, chart, compat in others:
        bonus = 15 if chart["pillars"]["day"]["stem"] // 2 == me_chart["lucky_element"] else 0
        v = compat + bonus + _digest(today, pid)[0] % 20
        if best is None or v > best[0]:
            best = (v, pid, name, bonus > 0)
    if not best:
        return None
    reason = ("내게 필요한 기운을 가진 사람이라" if best[3] else "오늘 기운이 잘 맞아서")
    return {"id": best[1], "name": best[2],
            "line": f"{reason} 같이 커피 한 잔 하면 운이 올라가요 ☕"}
