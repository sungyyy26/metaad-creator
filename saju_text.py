def chart_reading(chart):
    dm = DAY_MASTER[chart["day_master"]]
    counts = chart["element_counts"]
    tips = []
    weak, strong = chart["weak_element"], chart["strong_element"]
    if counts[weak] == 0 or counts[weak] < counts[strong]:
        tips.append(ELEMENT_TIPS["lack"][weak])
    if counts[strong] >= 3:
        tips.append(ELEMENT_TIPS["excess"][strong])
    lucky = chart["lucky_element"]
    areas = GROUP_AREAS[chart["dominant_group"]]
    return {
        "headline": f"{chart['day_animal']}의 기운을 가진 {STEMS[chart['day_master']]}{ELEMENTS[chart['day_master'] // 2]} 일간",
        "day_master": dm,
        "strength": STRENGTH[chart["strength"]],
        "element_tips": tips,
        "work": areas["work"], "money": areas["money"], "love": areas["love"],
        "lucky": {
            "element": f"{ELEMENT_EMOJI[lucky]} {ELEMENTS[lucky]}",
            "color": ELEMENT_COLOR[lucky], "number": ELEMENT_NUMBER[lucky],
            "direction": ELEMENT_DIRECTION[lucky], "item": ELEMENT_ITEM[lucky],
        },
    }


def daily_reading(chart, fortune):
    message = TODAY[fortune["ten_god"]][fortune["variant"]]
    extras = []
    if fortune["harmony"]:
        extras.append("오늘 일진이 내 일지와 합을 이뤄요. 사람 운이 좋아요 🤝")
    if fortune["clash"]:
        extras.append("오늘 일진이 내 일지와 충이에요. 서두르지 말고 한 번 더 확인!")
    if fortune["lucky_hit"]:
        extras.append("나에게 필요한 기운이 들어오는 날이라 운이 한층 밝아요 ✨")
    lucky = chart["lucky_element"]
    return {"message": message, "extras": extras,
            "lucky_color": ELEMENT_COLOR[lucky], "lucky_item": ELEMENT_ITEM[lucky]}


